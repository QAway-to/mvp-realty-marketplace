/**
 * Схема в базе, которой владеет это приложение.
 *
 * Таблицы не кладём в `public`: база может быть общей с другим сервисом, и тогда
 * `public` превращается в свалку, где чужая миграция способна задеть наши
 * таблицы, а наша — чужие. Отдельная схема разводит их физически: имена не
 * пересекаются, права выдаются отдельно, дамп можно снять только по своей части.
 *
 * Имя переопределяется переменной `DATABASE_SCHEMA` — на случай, когда в одной
 * базе живут стенд и продакшн.
 */

export const DATABASE_SCHEMA = process.env.DATABASE_SCHEMA ?? "realty";

/**
 * Возвращает строку подключения с нужной схемой.
 *
 * Параметр в URL перезаписывается сознательно: `schema=public`, забытый в
 * окружении, не должен тихо разложить таблицы по общей схеме. Пароль и остальные
 * параметры не трогаем.
 */
export function withSchema(
  connectionString: string,
  schema: string = DATABASE_SCHEMA,
): string {
  const url = new URL(connectionString);
  url.searchParams.set("schema", schema);
  return url.toString();
}
