/**
 * Пароли. Хеш bcrypt, сравнение — только через `compare`.
 *
 * Стоимость выбрана по замеру, а не по привычке. На этой машине `bcryptjs` —
 * чистый JS, без нативного модуля — даёт: стоимость 10 около 250 мс, 11 около
 * 435 мс, 12 от 840 мс до двух секунд. Инстанс Render получает долю процессора,
 * и там каждая цифра станет кратно больше.
 *
 * Поэтому 10: это общепринятый минимум, при котором перебор дорог, а вход не
 * занимает процессор на секунды. Секунды здесь не только неудобство, но и способ
 * положить сервис десятком попыток входа.
 *
 * Стоимость записана внутри самого хеша, поэтому её можно поднять когда угодно —
 * старые пароли продолжат проверяться. Сделать это стоит вместе с переходом на
 * платный инстанс.
 */

import bcrypt from "bcryptjs";

const COST = 10;

/** Ниже восьми символов не принимаем: остальное — дело политики, а не кода. */
export const MIN_PASSWORD_LENGTH = 8;

export const hashPassword = (plain: string): Promise<string> =>
  bcrypt.hash(plain, COST);

/**
 * `passwordHash` может отсутствовать: приглашённый пользователь ещё не задал
 * пароль. Такому входа нет, но отвечать надо так же долго, как при неверном
 * пароле, иначе по времени ответа видно, у кого пароль уже установлен.
 */
export async function verifyPassword(
  plain: string,
  passwordHash: string | null,
): Promise<boolean> {
  if (passwordHash === null) {
    await bcrypt.compare(plain, DUMMY_HASH);
    return false;
  }
  return bcrypt.compare(plain, passwordHash);
}

/**
 * Заведомо несовпадающий хеш той же стоимости — нужен только чтобы потратить
 * столько же времени, сколько уходит на настоящую проверку. Стоимость в нём
 * обязана совпадать с `COST`, иначе время ответа выдаёт, есть ли такой
 * пользователь. Это хеш случайной строки, а не пример из документации: широко
 * известный хеш подобрать не нужно, его достаточно узнать.
 */
const DUMMY_HASH =
  "$2b$10$CZ9K0az29iZCQ/14UnQkDuxdkKCcR8cb3jDIAeM2g476j9KVwuS0K";
